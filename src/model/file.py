import stat

from datetime import datetime, timezone
from hashlib import md5
from os import stat as os_stat
from os.path import (
    basename,
    exists,
    getctime,
    getmtime,
    getsize,
    join,
)
from typing import Union
from re import match


def is_hidden_file(file_path: str) -> bool:
    """
    (.*\\.bak$): Matches common backup files that end with .bak.
    (.*\\.tmp$): Matches generic temporary files that end with .tmp.
    (.*\\.temp$): Another suffix for temporary files, matches files that end with .temp.
    (.*\\.swp$): Matches common swap files that end with .swp, specific to many editors.
    (.*\\.swo$): Another type of swap file, usually generated by editors like Vim, that ends with .swo.
    (.*-\\d{4}-\\d{2}-\\d{2}-\\d{6}$): Matches backup files that follow a date-timestamp convention in the format -YYYY-MM-DD-HHmmss.

    Args:
        file_path (str): _description_

    Returns:
        bool: _description_
    """
    hidden_file_regex = r"(^\..*|.*~$|^4913$|^\..*\.sw[px]$|^\.~lock\..*#$|.*\.bak$|.*\.tmp$|.*\.temp$|.*\.swp$|.*\.swo$|.*-\d{4}-\d{2}-\d{2}-\d{6}$)"
    return bool(match(hidden_file_regex, basename(file_path)))


class File:
    def __init__(
        self,
        filepath: str = None,
        ctime: Union[str, int, float, datetime] = None,
        mtime: Union[str, int, float, datetime] = None,
        size: int = 0,
        md5sum: str = None,
        permissions: str = None,
    ):
        self.filepath = filepath
        self.name = basename(filepath) if filepath else None
        self.size = size
        self.md5sum = md5sum
        self.permissions = permissions
        self.ctime = self._parse_time(ctime)
        self.mtime = self._parse_time(mtime)

    def __repr__(self):
        return (
            f"{self.__class__.__name__}("
            f"filepath={self.filepath}, "
            f"name={self.name}, "
            f"ctime={self.ctime}, "
            f"mtime={self.mtime}, "
            f"size={self.size}, "
            f"md5sum={self.md5sum}, "
            f"permissions={self.permissions})"
        )

    def _parse_time(self, time: Union[str, int, float, datetime]) -> Union[int, None]:
        if isinstance(time, datetime):
            return int(time.timestamp())
        elif isinstance(time, str):
            return int(datetime.fromisoformat(time).timestamp())
        elif isinstance(time, int):
            return int(datetime.fromtimestamp(time, timezone.utc).timestamp())
        elif isinstance(time, float):
            return int(datetime.fromtimestamp(time, timezone.utc).timestamp())
        return None

    def _compute_md5(filepath):
        """Compute the MD5 checksum of a file."""
        with open(filepath, "rb") as f:
            return md5(f.read()).hexdigest()

    def _get_permissions(obj_path) -> str:
        obj_stat = os_stat(obj_path)
        permissions = obj_stat.st_mode
        return stat.filemode(permissions)

    def to_dict(self):
        return {
            "filepath": self.filepath,
            "name": self.name,
            "ctime": self.ctime,
            "mtime": self.mtime,
            "size": self.size,
            "md5sum": self.md5sum,
            "permissions": self.permissions,
        }

    @classmethod
    def get(cls, file_path: str, buckets_dir: str = None):
        file_path = (
            join(buckets_dir, file_path.lstrip("/")) if buckets_dir else file_path
        )
        if exists(file_path):
            return cls(
                filepath=file_path,
                ctime=int(getctime(file_path)),
                mtime=int(getmtime(file_path)),
                size=getsize(file_path),
                md5sum=cls._compute_md5(file_path),
                permissions=cls._get_permissions(file_path),
            )
        else:
            return None

    @classmethod
    def from_dict(
        cls,
        data: dict,
        dir_prefix: str = None,
        strip_dir_prefix: bool = True,
    ):
        if strip_dir_prefix and not dir_prefix:
            raise ValueError("Set dir_prefix to strip it.")
        filepath = (
            str(data.get("filepath")).removeprefix(dir_prefix).lstrip("/")
            if strip_dir_prefix
            else join(dir_prefix, data.get("filepath").lstrip("/"))
        )

        return cls(
            filepath=filepath,
            ctime=data.get("ctime", None),
            mtime=data.get("mtime", None),
            size=data.get("size", 0),
            md5sum=data.get("md5sum", None),
            permissions=data.get("permissions", None),
        )
